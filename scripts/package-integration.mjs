import {cp,mkdir,readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
const root=process.cwd(), pkg=JSON.parse(await readFile('integrations/package.json','utf8'));
const destination=resolve(process.argv[2]||`.runtime/dist/integration-${Date.now()}`);
await mkdir(destination,{recursive:true});
const plugin=resolve(destination,'plugins/agentic-browser');
await mkdir(plugin,{recursive:true});
for(const name of ['.codex-plugin','.claude-plugin','.mcp.json','mcp.claude.json'])await cp(resolve(root,'plugins/agentic-browser',name),resolve(plugin,name),{recursive:true});
for(const name of ['package.json','package-lock.json'])await cp(resolve(root,'integrations',name),resolve(plugin,name));
await cp('skills',resolve(plugin,'skills'),{recursive:true});
await mkdir(resolve(plugin,'src'),{recursive:true});
for(const name of ['mcp.ts','space-client.ts','plugin-mcp.mjs','page.mjs','agentic-browser.mjs'])await cp(resolve(root,'src',name),resolve(plugin,'src',name));
for(const name of ['.agents','.claude-plugin'])await cp(resolve(root,name),resolve(destination,name),{recursive:true});
await mkdir(resolve(destination,'scripts'),{recursive:true});
await cp('scripts/bind-space.mjs',resolve(destination,'scripts/bind-space.mjs'));
await cp('integrations/INSTALL.md',resolve(destination,'INSTALL.md'));
const archive=resolve(destination,`../agentic-browser-integration-${pkg.version}.tgz`);
execFileSync('tar',['-czf',archive,'-C',destination,'.']);
const sha=createHash('sha256').update(await readFile(archive)).digest('hex');
await writeFile(archive+'.sha256',`${sha}  ${archive.split('/').at(-1)}\n`);
console.log(JSON.stringify({directory:destination,archive,sha256:sha}));
